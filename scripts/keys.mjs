// Creates a fresh test account, writes it to .env and asks Studionet to fund it.
// Usage: node scripts/keys.mjs            (does nothing when .env already holds a DEPLOY_KEY)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";

const envUrl = new URL("../.env", import.meta.url);
if (existsSync(envUrl) && /^DEPLOY_KEY=0x[0-9a-fA-F]{64}/m.test(readFileSync(envUrl, "utf8"))) {
  console.log(".env already has a DEPLOY_KEY, nothing to do. Delete the file to start over.");
  process.exit(0);
}
const sdk = await import("genlayer-js");
const { studionet } = await import("genlayer-js/chains");
const RPC = studionet?.rpcUrls?.default?.http?.[0];
const key = "0x" + randomBytes(32).toString("hex");
writeFileSync(envUrl, ["# Generated by scripts/keys.mjs. A Studionet test account only; never put real funds on it.", `DEPLOY_KEY=${key}`, ""].join("\n"));
const address = sdk.createAccount(key).address;
console.log(`Wrote .env with a new account: ${address}`);
try {
  // The number is written by hand because JSON.stringify cannot carry a BigInt.
  const body = `{"jsonrpc":"2.0","id":1,"method":"sim_fundAccount","params":["${address}",1000000000000000000]}`;
  const res = await fetch(RPC, { method: "POST", headers: { "content-type": "application/json" }, body });
  const out = await res.json();
  if (out.error) throw new Error(out.error.message ?? JSON.stringify(out.error));
  console.log("Funded with 1 GEN.");
} catch (err) {
  console.log(`Not funded automatically (${String(err?.message ?? err).slice(0, 80)}). Fund it from the Studio faucet.`);
}
console.log("Load it with:  set -a; . ./.env; set +a");
